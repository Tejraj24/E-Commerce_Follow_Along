// Helper: get products by category
export const getProductsByCategory = (category: string): Product[] => {
  const normalised = category.toLowerCase();
  if (normalised === "shop" || normalised === "all" || normalised === "new-in") {
    return products;
  }
  return products.filter(
    (p) => p.category.toLowerCase() === normalised
  );
};

// Helper: get related products (same category or same collection, excluding self)
export const getRelatedProducts = (
  product: Product,
  limit = 8
): Product[] => {
  const sameCollection = products.filter(
    (p) => p.collection === product.collection && p.id !== product.id
  );
  if (sameCollection.length >= limit) return sameCollection.slice(0, limit);
  const sameCategory = products.filter(
    (p) =>
      p.category === product.category &&
      p.id !== product.id &&
      !sameCollection.find((s) => s.id === p.id)
  );
  return [...sameCollection, ...sameCategory].slice(0, limit);
};
